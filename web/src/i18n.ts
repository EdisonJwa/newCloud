// Internationalisation.
//
// Messages are looked up by key and interpolated as whole templates. No string concatenation
// anywhere: word order differs between languages, and a sentence assembled from fragments
// cannot be translated. Plurals go through Intl.PluralRules, numbers and dates through Intl,
// so nothing here assumes a decimal separator, a 12-hour clock or a week start.
//
// ## Two rules that keep this file honest
//
// 1. **Every key the code references exists in English.** A missing key does not fail the
//    compiler — `t()` renders the key itself, so the interface shows `acl.grant` where a button
//    label should be. `pnpm i18n` walks the source and fails on a reference with no entry.
//
// 2. **Every English key exists in every other language**, except plural forms the language's
//    own rules can never select. The exemption is computed from `Intl.PluralRules`, not
//    hand-listed, because a hand-listed exemption is how a real omission gets pardoned.
//
// ## Why some keys are dynamically composed
//
// `theme.${value}`, `kind.${preview}`, `admin.status.${status}` and `settings.subtitle.${tab}`
// are closed sets whose members are all present in both tables. Composing them keeps a
// three-option segmented control to one map call instead of a lookup table beside a switch, and
// the parity check still sees every member because they are literal keys in the tables below.

