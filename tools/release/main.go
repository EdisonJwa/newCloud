// Command release builds the release artefacts: one binary per platform, the SBOM, and a checksum
// file, all into one directory.
//
// This used to be a shell script inside the Makefile, and it did not run on Windows: make invoked
// `rm -rf`, `for p in ...` and `sha256sum` directly, and none of those exist there, so the documented
// release path failed with "그런 파일을 찾을 수 없음" on the same machine the project is developed on.
// The GitHub workflow did not catch it because it runs on Linux.
//
// Go is present by definition — it is what builds the binary — so the pipeline is written in it and
// the Makefile target becomes one line. That also makes the steps testable, which the shell version
// never was.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	var (
		dist      = flag.String("dist", "dist", "output directory, removed and recreated")
		version   = flag.String("version", "dev", "version stamped into the binaries")
		platforms = flag.String("platforms", "linux/amd64", "comma-separated GOOS/GOARCH list")
		ldflags   = flag.String("ldflags", "", "linker flags")
		goBin     = flag.String("go", "go", "the go command to build with")
	)
	flag.Parse()

	if err := run(*goBin, *dist, *version, *platforms, *ldflags); err != nil {
		fmt.Fprintf(os.Stderr, "release: %v\n", err)
		os.Exit(1)
	}
}

func run(goBin, dist, version, platforms, ldflags string) error {
	// A stale directory is worse than a missing one: it would ship last release's binary under this
	// release's name, and the checksum file would happily attest to it.
	if err := os.RemoveAll(dist); err != nil {
		return fmt.Errorf("clear %s: %w", dist, err)
	}
	if err := os.MkdirAll(dist, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", dist, err)
	}

	// Build from the module root, not from wherever the tool was invoked: the packages below are
	// named relative to it, and a release run from tools/release (which is where the test runs)
	// would otherwise fail to resolve them.
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	dist, err = filepath.Abs(dist)
	if err != nil {
		return fmt.Errorf("resolve %s: %w", dist, err)
	}

	// The Makefile passes PLATFORMS as a single space-separated string, and a caller typing the flag
	// by hand tends to use commas. Accept both rather than making that a trap.
	for _, p := range strings.Split(strings.ReplaceAll(platforms, ",", " "), " ") {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		goos, goarch, ok := strings.Cut(p, "/")
		if !ok {
			return fmt.Errorf("platform %q is not GOOS/GOARCH", p)
		}
		out := filepath.Join(dist, fmt.Sprintf("newcloud-%s-%s-%s", version, goos, goarch))
		if goos == "windows" {
			out += ".exe"
		}
		fmt.Printf("  %s/%s\n", goos, goarch)

		args := []string{"build", "-trimpath", "-o", out}
		if ldflags != "" {
			args = append(args, "-ldflags", ldflags)
		}
		args = append(args, "./cmd/newcloud")

		cmd := exec.Command(goBin, args...)
		cmd.Dir = root
		// CGO off is what makes one toolchain enough for every target: the binary is pure Go.
		cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS="+goos, "GOARCH="+goarch)
		cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("build %s/%s: %w", goos, goarch, err)
		}
	}

	// The SBOM is generated by the same command the Makefile target used, so the artefact that ships
	// and the artefact that can be rebuilt from a checkout are produced by one implementation.
	sbom := exec.Command(goBin, "run", "./tools/sbom",
		"-version", version, "-o", filepath.Join(dist, "sbom.cdx.json"))
	sbom.Dir = root
	sbom.Stdout, sbom.Stderr = os.Stdout, os.Stderr
	if err := sbom.Run(); err != nil {
		return fmt.Errorf("generate SBOM: %w", err)
	}
	fmt.Println("wrote", filepath.Join(dist, "sbom.cdx.json"))

	if err := writeChecksums(dist, "SHA256SUMS"); err != nil {
		return err
	}
	return nil
}

// writeChecksums hashes every file in dir, in a stable order, into a single file.
//
// Directory order is not stable across filesystems, so the entries are sorted: an operator comparing
// two releases should see a diff only where something actually changed.
func writeChecksums(dir, name string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("read %s: %w", dir, err)
	}

	var names []string
	for _, e := range entries {
		if !e.IsDir() && e.Name() != name {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		return fmt.Errorf("no artefacts in %s: a checksum file over nothing would look like success", dir)
	}

	var sb strings.Builder
	for _, n := range names {
		sum, serr := fileSHA256(filepath.Join(dir, n))
		if serr != nil {
			return serr
		}
		fmt.Fprintf(&sb, "%s  %s\n", sum, n)
	}
	if err := os.WriteFile(filepath.Join(dir, name), []byte(sb.String()), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", name, err)
	}
	fmt.Println("wrote", filepath.Join(dir, name))
	return nil
}

// moduleRoot walks up from the working directory to the directory holding go.mod.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, serr := os.Stat(filepath.Join(dir, "go.mod")); serr == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above %s: run this from inside the module", dir)
		}
		dir = parent
	}
}

func fileSHA256(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()

	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", fmt.Errorf("hash %s: %w", path, err)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}
